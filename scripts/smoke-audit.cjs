const fs=require('node:fs'),zlib=require('node:zlib'),assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const dom=new JSDOM(html,{url:'https://citroen.example/#auditoria',runScripts:'outside-only',virtualConsole:new VirtualConsole()});
const w=dom.window;
w.eval(fs.readFileSync('data/auditoria_2026.js','utf8'));
w.eval(fs.readFileSync('data/proyecciones_2026.js','utf8'));
const packed=JSON.parse(zlib.gunzipSync(Buffer.from(w.CITROEN_PLAN_PACKED,'base64')).toString('utf8'));
w.DecompressionStream=class{constructor(type){assert.equal(type,'gzip');}};
w.Blob=class{stream(){return{pipeThrough(){return null;}};}};
w.Response=class{async text(){return JSON.stringify(packed);}};
w.eval(fs.readFileSync('audit.js','utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
(async()=>{
 const id=x=>w.document.getElementById(x);
 for(let i=0;i<30&&!id('auditStats').querySelector('.cit-audit-stat');i++)await new Promise(r=>setTimeout(r,0));
 assert.ok(id('auditStatus').textContent.includes('reconciliada'),'Audit did not reconcile: '+id('auditStatus').textContent);
 assert.equal(id('auditStats').querySelectorAll('.cit-audit-stat').length,6,'Six audited summary KPIs');
 assert.equal(id('auditMonthRows').querySelectorAll('tr').length,10,'Ten monthly audits');
 assert.equal(id('auditMonth').options.length,11,'10 filterable months');
 assert.ok(id('auditBaseHero').textContent.includes('944'),'The audited base budget');
 assert.ok(id('auditStats').textContent.includes('99.969'),'The comparable five-model lead total must appear');
 assert.ok(id('auditStats').textContent.includes('105.300'),'The mixed BOT lead total must be labeled separately');
 assert.equal(id('auditModelRows').querySelectorAll('tr').length,60,'All 60 model-month targets');
 assert.equal(id('auditScenarioList').querySelectorAll('.cit-scenario').length,6,'All six scenario documents');
 assert.equal(id('auditAlertList').querySelectorAll('.cit-audit-issue').length,30,'All 30 cell-cited alerts');
 const select=(key,value)=>{id(key).value=value;id(key).dispatchEvent(new w.Event('change'));};
 select('auditMonth','2026-09');
 assert.equal(id('auditMonthRows').querySelectorAll('tr').length,1,'September month filter');
 assert.equal(id('auditModelRows').querySelectorAll('tr').length,6,'Six model targets in September');
 select('auditSeverity','Alta');
 assert.ok(id('auditAlertList').querySelectorAll('.cit-audit-issue').length>=1,'High-priority September alerts');
 select('auditView','alerts');
 assert.ok(!w.document.querySelector('[data-audit-panel="alerts"]').hidden,'Active audit panel visible');
 assert.ok(w.document.querySelector('[data-audit-panel="months"]').hidden,'Inactive audit panel hidden');
 id('auditReset').click();
 assert.equal(id('auditMonthRows').querySelectorAll('tr').length,10,'Reset restored monthly reconciliation');
 assert.equal(id('auditAlertList').querySelectorAll('.cit-audit-issue').length,30,'Reset restored findings');
 console.log('PASS: 10 source Excels, 60 model-month targets, 6 alternate scenarios, 30 alerts, clean audit filters and totals.');
 w.close();
})().catch(e=>{console.error(e);process.exitCode=1;w.close();});
