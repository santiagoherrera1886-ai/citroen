const assert=require('node:assert/strict');
const {compare,value}=require('../period-compare.js');
const rows=[];
for(let i=1;i<=30;i++)rows.push({month:'2026-09',date:'2026-09-'+String(i).padStart(2,'0'),spend:100,forms:1,clicks:10,impressions:1000,messages:1});
for(let i=1;i<=20;i++)rows.push({month:'2026-10',date:'2026-10-'+String(i).padStart(2,'0'),spend:200,forms:2,clicks:30,impressions:1500,messages:3});
const spend=compare(rows,'spend');
assert.equal(spend.ok,true);
assert.equal(spend.previousMonth,'2026-09');
assert.equal(spend.currentMonth,'2026-10');
assert.equal(spend.cutoffDay,20,'October partial data sets same-day cutoff');
assert.equal(spend.previous,2000,'September is correctly truncated to the twentieth');
assert.equal(spend.current,4000);
assert.equal(spend.change,100);
assert.equal(spend.currentRows,20);
assert.equal(spend.previousRows,20);
const leads=compare(rows,'forms');
assert.equal(leads.previous,20);assert.equal(leads.current,40);assert.equal(leads.change,100);
const cpl=compare(rows,'cpl');
assert.equal(cpl.previous,100);assert.equal(cpl.current,100);assert.equal(cpl.change,0);
const ctr=compare(rows,'ctr');
assert.equal(ctr.previous,1);assert.equal(ctr.current,2);assert.equal(ctr.change,100,'CTR based on clicks over impressions per period');
assert.equal(compare(rows.filter(r=>r.month==='2026-10'),'forms').ok,false,'Month-only filter must not invent a baseline');
const zeros=compare(rows.map(x=>({...x,forms:x.month==='2026-09'?0:x.forms})),'forms');
assert.equal(zeros.previous,0);assert.equal(zeros.change,null,'No infinite percentage change when denominator is zero');
assert.equal(value('cpl',rows.filter(x=>x.month==='2026-09').map(x=>({...x,forms:0}))),null);
const bound=compare(rows,'reach',{reachEstimator:(numbers,universe)=>{assert.equal(universe,15000000);return Math.min(universe,numbers.reduce((a,v)=>a+v,0));}});
assert.equal(bound.ok,true);
assert.equal(bound.favorable,'neutral','No bogus green/red positive when reach unchanged');
const reverse=compare(rows,'cpl');
assert.equal(reverse.favorable,'neutral');
assert.equal(compare(rows,'fake').ok,false,'Unsupported fields must be rejected');
console.log('PASS: month-to-date parity, percentage deltas, CPL and CTR ratios, sparse filters, zero baseline, Sainsbury reach placeholder and no invented months.');
