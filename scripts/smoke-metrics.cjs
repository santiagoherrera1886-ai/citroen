/* Integration test for Looker-style Citroen metrics inspector. Real 2026 source packs, no mocks of metrics. */
const fs=require('node:fs'),zlib=require('node:zlib'),assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://citroen.example/#resumen',runScripts:'outside-only',virtualConsole:new VirtualConsole()});
const w=dom.window;
const $=id=>w.document.getElementById(id);
w.eval(fs.readFileSync('data/proyecciones_2026.js','utf8'));
w.eval(fs.readFileSync('data/revision_2026.js','utf8'));

w.eval(fs.readFileSync('reach-math.js','utf8'));
assert.equal(w.CITROEN_REACH_MATH.estimate([50,40],100),70,'Sainsbury should exclude probable overlap: 50 + 40 - 20');
assert.equal(w.CITROEN_REACH_MATH.estimate([80,80],100),96,'Sainsbury two 80% audiences should estimate 96%');
assert.equal(w.CITROEN_REACH_MATH.estimate([50,40],null),null,'Universe is mandatory');
assert.equal(w.CITROEN_REACH_MATH.estimate([110,40],100),null,'Unrealistic reach larger than universe is invalid');

const daily=JSON.parse(fs.readFileSync('data/meta_2026_daily.json','utf8'));
const detail=JSON.parse(fs.readFileSync('data/meta_2026_detail.json','utf8'));
w.DecompressionStream=class{constructor(type){assert.equal(type,'gzip');}};
w.Blob=class{constructor(parts){this.parts=parts;}stream(){const that=this;return{pipeThrough(){return that;}};}};
w.Response=class{constructor(stream){this.stream=stream;}async text(){return zlib.gunzipSync(Buffer.from(this.stream.parts[0])).toString('utf8');}};
w.fetch=async url=>({ok:true,json:async()=>String(url).includes('detail')?detail:daily});
w.confirm=()=>true;
for(const file of ['concept3.js','studio.js','metric-editor.js'])w.eval(fs.readFileSync(file,'utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
const pause=()=>new Promise(r=>setTimeout(r,0));
(async()=>{
 for(let i=0;i<60&&(!$('c3Kpis').querySelector('.c3-kpi')||!$('studioCards').querySelector('.studio-native-tools'));i++)await pause();
 assert.equal($('c3Kpis').querySelectorAll('.c3-kpi').length,6,'Six visible KPIs');
 assert.ok($('c3Kpis').textContent.includes('145.525.157'),'Original impressions KPI present');
 assert.equal($('metricInspector').hidden,true,'Properties rail hidden outside edit mode');
 $('studioEdit').click();
 assert.equal($('metricInspector').hidden,false,'Properties rail appears when editing');
 assert.ok($('metricCurrent').textContent.includes('Indicador 6'),'Default selects sixth KPI');
 assert.ok($('metricFields').querySelector('[data-field="reach"]'),'Reach field listed in right rail');
 $('metricFields').querySelector('[data-field="reach"]').click();
 assert.ok($('c3Kpis').querySelector('[data-metric-slot="5"]').textContent.includes('Alcance estimado'),'KPI switches to Sainsbury-estimated reach');
 assert.ok($('c3Kpis').querySelector('[data-metric-slot="5"]').textContent.includes('—'),'Reach cannot be invented without universe');
 assert.ok(!$('c3Kpis').textContent.includes('113.191.745'),'The former gross reach sum must never appear as net reach');
 assert.ok($('metricNote').textContent.toLowerCase().includes('no representa'),'Reach is identified as an estimate');
 const u=$('metricUniverse');u.value='15000000';u.dispatchEvent(new w.Event('change',{bubbles:true}));
 const expected=w.CITROEN_REACH_MATH.estimate(daily.daily.map(r=>r[10]||0),15000000);
 const formatted=new Intl.NumberFormat('es-CO').format(expected);
 assert.ok(expected>0&&expected<=15000000&&expected!==113191745,'Sainsbury should be bounded by universe, never the original summed reach');
 assert.ok($('c3Kpis').querySelector('[data-metric-slot="5"]').textContent.includes(formatted),'KPI should show modelled reach '+formatted);
 assert.equal(w.CITROEN_METRIC_OVERRIDES.universe,15000000,'Universe is saved in model');
 assert.equal(w.CITROEN_METRIC_OVERRIDES.slots[5],'reach','Selection stored in shared data settings');
 $('c3ComparePanel').click();
 $('metricFields').querySelector('[data-field="reach"]').click();
 assert.ok($('c3CompareNote').textContent.includes('Sainsbury')&&$('c3CompareNote').textContent.includes('no usuarios únicos'),'Comparison reach shows only actual data and warns about aggregation: '+$('c3CompareNote').textContent+' | '+JSON.stringify(w.CITROEN_METRIC_OVERRIDES.native));
 w.document.querySelector('[data-c3-metric="investment"]').click();
 assert.equal(w.CITROEN_METRIC_OVERRIDES.native.compareMetric,'investment','Original comparison metric button updates sidebar settings');

 const note=w.localStorage.getItem('citroen_metric_preferences_v1');
 assert.ok(note.includes('"reach"'),'Reach saved to browser');
 $('c3FunnelPanel').click();
 assert.ok($('metricFields').querySelector('[data-field="reach"]'),'Funnel supports choosing reach');
 $('metricFields').querySelector('[data-field="reach"]').click();
 assert.ok($('c3Funnel').textContent.includes('Alcance estimado'),'Funnel stage changes to reach');
 assert.ok($('c3Funnel').textContent.includes('Clics / alcance'),'Funnel uses a correctly renamed ratio');
 assert.ok(!$('c3Funnel').textContent.includes('CTR de enlace'),'Funnel no longer mislabels ratio as CTR');
 $('c3ModelsPanel').click();
 $('metricFields').querySelector('[data-field="reach"]').click();
 assert.ok($('c3Models').textContent.includes('Alcance estimado'),'Model tiles update primary KPI');
 $('c3CampaignPanel').click();
 $('metricFields').querySelector('[data-field="reach"]').click();
 assert.ok($('c3CampaignPanel').querySelector('thead').textContent.includes('Alcance estimado'),'Campaign table column changes');
 $('studioAdd').click();
 const card=$('studioCards').querySelector('.studio-card');
 assert.ok(card,'Custom graph created');
 const src=card.querySelector('[data-control="source"]');
 src.value='meta';src.dispatchEvent(new w.Event('change',{bubbles:true}));
 assert.ok($('metricFields').querySelector('[data-field="reach"]'),'New Meta graph offers reach');
 $('metricFields').querySelector('[data-field="reach"]').click();
 const newCard=$('studioCards').querySelector('.studio-card');
 assert.equal(newCard.querySelector('[data-control="metric"]').value,'reach','Custom graph switched to reach');
 assert.ok(newCard.querySelector('svg'),'Custom graph still draws with real data');
 $('studioEdit').click();
 assert.equal($('metricInspector').hidden,true,'Closing edit mode closes properties rail');
 assert.ok($('c3Kpis').textContent.includes(formatted),'View mode keeps Sainsbury estimate');
 console.log('PASS: six KPIs, Sainsbury reach replacement (with explicit universe), funnel ratio correction, models, campaign metric column, custom chart, saved preferences and edit visibility.');
 w.close();
})().catch(e=>{console.error(e);process.exitCode=1;w.close();});
