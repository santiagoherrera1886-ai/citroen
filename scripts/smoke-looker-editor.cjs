/* Smoke test for Citroen Looker-like workspace. No network credentials required. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM,VirtualConsole}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://citroen.example/#resumen',runScripts:'outside-only',virtualConsole:new VirtualConsole()});
const w=dom.window,$=id=>w.document.getElementById(id);
let edits=0,charts=0,pages=0,styles=0,metricClicks=0;
$('studioEdit').addEventListener('click',()=>{edits++;$('c3Dashboard').classList.toggle('studio-edit-on');w.document.dispatchEvent(new w.Event('citroen:studio-layout'));});
$('builderNewPage').addEventListener('click',()=>pages++);
$('studioGallery').querySelector('[data-gallery-chart="bar"]').addEventListener('click',()=>charts++);
w.CITROEN_STYLE_EDITOR={applyGlobalPalette:()=>{styles++}};
const metric=w.document.createElement('button');metric.dataset.field='spend';metric.onclick=()=>metricClicks++;$('metricFields').appendChild(metric);
w.eval(fs.readFileSync('looker-editor.js','utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
const shell=$('lookerEditorShell');
assert.ok(shell,'Editor shell inserted');
assert.equal(shell.hidden,true,'No editor shell for public viewer');
assert.equal(w.document.body.classList.contains('citroen-looker-edit'),false,'Read-only view remains untouched');
$('c3Dashboard').classList.add('studio-edit-on');w.document.dispatchEvent(new w.Event('citroen:studio-layout'));
assert.equal(shell.hidden,false,'Authenticated edit state reveals shell');
assert.ok(w.document.body.classList.contains('citroen-looker-edit'),'Full-screen editing class enabled');
assert.ok($('lePageList').querySelector('[data-page="resumen"]'),'Pages rail includes Resumen');
assert.ok($('leFieldsList').querySelector('[data-field-key="spend"]'),'Source catalog includes investment');
w.document.querySelector('[data-menu="insertar"]').click();
assert.equal($('leDropdown').hidden,false,'Insertion menu opens');
assert.ok($('leDropdown').textContent.includes('Añadir gráfico'),'Insertion menu lists chart tools');
w.document.querySelector('[data-menu="chart"]').click();
assert.ok($('leDropdown').textContent.includes('Barras'),'Charts menu lists type');
$('leDropdown').querySelector('[data-command="bar"]').click();
assert.equal(charts,1,'Add chart delegates to existing working visual builder');
w.document.querySelector('[data-do="page"]').click();
assert.equal(pages,1,'Add page delegates to existing page builder');
w.document.querySelector('[data-menu="theme"]').click();
$('leDropdown').querySelector('[data-command="palette:montecarlo"]').click();
assert.equal(styles,1,'Theme controls use existing style engine');
$('leFieldsList').querySelector('[data-field-key="spend"]').click();
assert.equal(metricClicks,1,'Searchable data field applies selected metric');
$('leFieldSearch').value='cpl';$('leFieldSearch').dispatchEvent(new w.Event('input'));
assert.equal($('leFieldsList').querySelectorAll('[data-field-key]').length,1,'Field search updates catalog');
w.document.dispatchEvent(new w.CustomEvent('citroen:selection-changed',{detail:{key:'n:c3ComparePanel'}}));
assert.ok($('leToolbarStatus').textContent.includes('Editando:'),'Context panel selection status visible');
$('leView').click();
assert.equal(edits,1,'View action leaves editing via actual studio toggle');
assert.equal(shell.hidden,true,'Shell disappears in viewing mode');
assert.equal(w.document.body.classList.contains('citroen-looker-edit'),false,'Read-only layout fully restored');
console.log('PASS: guest view, desktop authoring shell, working toolbar/menus, pages, field search, theme, contextual selection and exit-to-view.');
w.close();