/* Citroen creator ribbon, quick themes and user media manager integration. */
const fs=require('node:fs'),zlib=require('node:zlib'),assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://citroen.example/#resumen',runScripts:'outside-only',virtualConsole:new VirtualConsole()});
const w=dom.window,$=id=>w.document.getElementById(id);
w.eval(fs.readFileSync('data/proyecciones_2026.js','utf8'));
w.eval(fs.readFileSync('data/revision_2026.js','utf8'));
w.eval(fs.readFileSync('reach-math.js','utf8'));
w.DecompressionStream=class{constructor(type){assert.equal(type,'gzip')}};
w.Blob=class{constructor(parts){this.parts=parts}stream(){const that=this;return{pipeThrough(){return that}}}};
w.Response=class{constructor(stream){this.stream=stream}async text(){return zlib.gunzipSync(Buffer.from(this.stream.parts[0])).toString('utf8')}};
const actual=JSON.parse(fs.readFileSync('data/meta_2026_daily.json','utf8')),detail=JSON.parse(fs.readFileSync('data/meta_2026_detail.json','utf8'));
w.fetch=async url=>({ok:true,json:async()=>String(url).includes('detail')?detail:actual});
w.confirm=()=>true;
w.CITROEN_ACCESS={canEdit:()=>true,requestEdit:()=>{w.CITROEN_STUDIO_UNLOCK?.();return Promise.resolve(true);}};
for(const file of ['concept3.js','studio.js','metric-editor.js','style-engine.js','photo-editor.js'])w.eval(fs.readFileSync(file,'utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
const pause=()=>new Promise(r=>setTimeout(r,0));
(async()=>{
 for(let i=0;i<80&&(!$('studioCards').querySelector('.studio-native-tools')||!$('c3Models').querySelector('.c3-model-card'));i++)await pause();
 assert.equal($('studioGallery').querySelectorAll('[data-gallery-chart]').length,6,'Six chart gallery entries available');
 assert.equal($('studioTools').hidden,true,'Creation ribbon hidden in view mode');
 $('studioEdit').click();
 assert.equal($('studioTools').hidden,false,'Creation ribbon visible in edit mode');
 $('studioGallery').querySelector('[data-gallery-chart="area"][data-gallery-source="meta"]').click();
 let cards=$('studioCards').querySelectorAll('.studio-card');
 assert.equal(cards.length,1,'Chart gallery adds directly to Resumen');
 assert.equal(cards[0].querySelector('[data-control="chart"]').value,'area','Area choice is applied');
 assert.equal(cards[0].querySelector('[data-control="source"]').value,'meta','Meta Ads source selected');
 assert.ok(cards[0].querySelector('svg polygon'),'Area chart uses filled shape');
 $('studioGallery').querySelector('[data-gallery-source="compare"]').click();
 cards=$('studioCards').querySelectorAll('.studio-card');
 assert.equal(cards.length,2,'Comparison gallery adds a second panel');
 assert.equal(cards[1].querySelector('[data-control="source"]').value,'compare','Plan / Meta comparison source is correct');
 $('studioThemes').click();
 assert.equal($('studioQuickThemes').hidden,false,'Quick palette menu expands');
 $('studioQuickThemes').querySelector('[data-global-palette="emerald"]').click();
 assert.equal($('c3FunnelPanel').style.getPropertyValue('--studio-primary'),'#0b9e85','Global theme colors native panels');
 assert.equal($('c3Kpis').querySelector('.c3-kpi').style.getPropertyValue('--studio-primary'),'#0b9e85','Global theme colors KPIs');
 assert.equal(cards[0].style.getPropertyValue('--studio-primary'),'#0b9e85','Global theme colors custom panels');
 $('studioPhotos').click();
 assert.equal($('studioPhotoDialog').hidden,false,'Photos modal opens');
 assert.equal($('studioPhotoModels').querySelectorAll('[data-photo-model]').length,5,'Four models and hero image are editable');
 const url='https://example.com/citroen-c3-custom.jpg';
 const input=$('studioPhotoModels').querySelector('[data-photo-url="C3"]');input.value=url;
 $('studioPhotoModels').querySelector('[data-photo-apply="C3"]').click();
 assert.equal(w.CITROEN_PHOTO_EDITOR.export().C3,url,'User photo URL stored');
 assert.equal($('c3Models').querySelector('.c3-model-photo img').getAttribute('src'),url,'Model photo updated on Resumen');
 assert.ok(w.localStorage.getItem('citroen_vehicle_images_v1').includes(url),'Image preference persisted locally');
 w.CITROEN_PHOTO_EDITOR.set('HERO','https://example.com/hero-aircross.jpg');
 assert.equal($('c3HeroCar').getAttribute('src'),'https://example.com/hero-aircross.jpg','Hero can be replaced');
 $('studioPhotoModels').querySelector('[data-photo-reset="C3"]').click();
 assert.ok(!$('c3Models').querySelector('.c3-model-photo img').getAttribute('src').includes('example.com'),'Original C3 image restores');
 assert.equal(w.CITROEN_PHOTO_EDITOR.export().C3,undefined,'Reset deletes only the selected vehicle override');
 w.CITROEN_PHOTO_EDITOR.replace({C3:url});
 assert.equal(w.CITROEN_PHOTO_EDITOR.export().C3,url,'Image preferences can be imported');
 assert.equal(w.CITROEN_PHOTO_EDITOR.set('C3','javascript:alert(1)'),false,'Unsafe image URLs rejected');
 $('studioPhotoClose').click();assert.equal($('studioPhotoDialog').hidden,true,'Media modal closes');
 $('studioEdit').click();assert.equal($('studioTools').hidden,true,'Ribbon hidden in view mode');
 assert.equal($('c3HeroCar').getAttribute('src'),'https://example.com/hero-aircross.jpg','Hero customization persists after ending edit');
 console.log('PASS: chart thumbnail creation, comparative chart, global palette, five image targets, HTTPS URL, local persistence, restore and view mode.');
 w.close();
})().catch(e=>{console.error(e);process.exitCode=1;w.close()});