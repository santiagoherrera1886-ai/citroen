const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const dom=new JSDOM('<!doctype html><body><main id="c3Dashboard"><div class="c3-header"><div><h1>Citroën</h1></div><div class="c3-header-controls"><label><select id="c3Month"><option value="">Mes</option></select></label><label><select id="c3Territory"><option value="">Territorio</option></select></label><label><select id="c3Model"><option value="">Modelo</option></select></label></div></div><div class="c3-hero">Banner</div><p id="c3Context">Reporte</p><div id="lkGlobalFilters"></div><div id="studioTools" hidden></div><div id="c3Kpis">'+
 Array.from({length:6},(_,i)=>'<article class="c3-kpi" data-metric-slot="'+i+'">KPI '+i+'</article>').join('')+
 '</div><section id="studioCards"><article id="c3ComparePanel" class="c3-panel" data-panel-key="n:c3ComparePanel">Chart</article><article class="studio-card" data-panel-key="c:mychart">Custom chart</article></section><button id="studioFreeLayout" type="button">Position</button></main></body>',{runScripts:'outside-only',url:'https://citroen-rho.vercel.app'});
const w=dom.window,$=id=>w.document.getElementById(id);
let editor=true,selected=0;
w.CITROEN_ACCESS={canEdit:()=>editor};
w.CITROEN_EDITOR_ZOOM=1;
$('c3Kpis').addEventListener('click',()=>selected++);
for(const id of ['c3Kpis','studioCards'])$(id).getBoundingClientRect=()=>({left:0,top:0,width:1260,height:630});
w.eval(fs.readFileSync('free-layout.js','utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
$('c3Dashboard').classList.add('studio-edit-on');
w.document.dispatchEvent(new w.Event('citroen:studio-layout'));
const lay=w.CITROEN_FREE_LAYOUT.export();
assert.equal(lay.enabled,true,'Opening edit mode automatically enables direct placement');
assert.equal(Object.keys(lay.items).length,8,'All six KPI cards plus two charts are positioned');
assert.ok($('c3Kpis').classList.contains('citroen-free-kpis'),'KPIs receive their own free-layout surface');
assert.ok($('studioCards').classList.contains('citroen-free-mode'),'Native graphs enter drag mode without toolbar click');
assert.ok($('c3ComparePanel').querySelector('.citroen-free-resize'),'Every native chart has a resize corner');
assert.ok($('c3Kpis').querySelector('.citroen-free-resize'),'Every KPI has a resize corner');
const k=$('c3Kpis').querySelector('[data-metric-slot="1"]');
const initial=w.CITROEN_FREE_LAYOUT.export().items['k:1'].x;
const ptr=(target,type,x,y)=>{const ev=new w.MouseEvent(type,{bubbles:true,cancelable:true,button:0,clientX:x,clientY:y});Object.defineProperty(ev,'pointerId',{value:42});target.dispatchEvent(ev);};
ptr(k,'pointerdown',200,60);
assert.equal(selected,1,'Direct pointerdown selects KPI immediately');
ptr(w,'pointermove',260,85);
ptr(w,'pointerup',260,85);
const moved=w.CITROEN_FREE_LAYOUT.export().items['k:1'].x;
assert.ok(moved>initial,'User drags KPI by clicking anywhere on its surface');
const native=$('c3ComparePanel'),start=w.CITROEN_FREE_LAYOUT.export().items['n:c3ComparePanel'];
ptr(native,'pointerdown',40,150);ptr(w,'pointermove',130,210);ptr(w,'pointerup',130,210);
const afterMove=w.CITROEN_FREE_LAYOUT.export().items['n:c3ComparePanel'];
assert.ok(afterMove.x>start.x&&afterMove.y>start.y,'Native chart moves directly from its body');
const corner=native.querySelector('.citroen-free-resize'),before=afterMove.w;
ptr(corner,'pointerdown',300,300);ptr(w,'pointermove',390,390);ptr(w,'pointerup',390,390);
assert.ok(w.CITROEN_FREE_LAYOUT.export().items['n:c3ComparePanel'].w>before,'Native chart resizes from selection corner');
editor=false;$('c3Dashboard').classList.remove('studio-edit-on');
w.document.dispatchEvent(new w.Event('citroen:studio-layout'));
assert.equal(native.querySelector('.citroen-free-resize'),null,'No editing resize handles leak into reader mode');
assert.equal(w.CITROEN_FREE_LAYOUT.export().items['k:1'].x,moved,'Position persists after editing ends');
w.CITROEN_FREE_LAYOUT.import(lay);
assert.ok(Object.keys(w.CITROEN_FREE_LAYOUT.export().items).includes('k:5'),'Published import accepts KPI placements');
console.log('PASS: Automatic editor drag, direct card selection, KPI dragging, native graph drag/resize and persisted layout without editor affordances in viewer mode.');
w.close();