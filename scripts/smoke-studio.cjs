/* Regression smoke test: editable Citroen custom report builder with real source packs. */
const fs=require('node:fs'),zlib=require('node:zlib'),assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'https://citroen.example/#studio',runScripts:'outside-only',virtualConsole:new VirtualConsole()});
const w=dom.window;
w.eval(fs.readFileSync('data/proyecciones_2026.js','utf8'));
w.eval(fs.readFileSync('data/revision_2026.js','utf8'));
w.DecompressionStream=class{constructor(type){assert.equal(type,'gzip');}};
w.Blob=class{constructor(parts){this.parts=parts;}stream(){const parent=this;return {pipeThrough(){return parent;}};}};
w.Response=class{constructor(stream){this.stream=stream;}async text(){return zlib.gunzipSync(Buffer.from(this.stream.parts[0])).toString('utf8');}};
const actuals=JSON.parse(fs.readFileSync('data/meta_2026_daily.json','utf8'));
w.fetch=async url=>({ok:true,json:async()=>actuals});
w.confirm=()=>true;
w.eval(fs.readFileSync('studio.js','utf8'));
w.document.dispatchEvent(new w.Event('DOMContentLoaded',{bubbles:true}));
(async()=>{
 const id=x=>w.document.getElementById(x);
 const pause=()=>new Promise(r=>setTimeout(r,0));
 for(let i=0;i<40&&!id('studioCards').querySelector('.studio-card');i++)await pause();
 assert.equal(id('studioCards').querySelectorAll('.c3-panel').length,5,'Five original widgets remain on the Resumen');
 assert.equal(id('studioCards').querySelectorAll('.studio-card').length,0,'No duplicate default custom charts');
 assert.equal(id('studioTools').hidden,true,'Editor collapsed initially');
 assert.ok(id('resumen').contains(id('studioCards')),'Editor canvas must be located inside Resumen');
 assert.ok(!w.document.querySelector('.nav-link[data-target="studio"]'),'Standalone editor navigation removed');
 for(const hidden of ['medios','creativos','datos'])assert.ok(!w.document.querySelector('.nav-link[data-target="'+hidden+'"]'),'Retired navigation '+hidden);
 assert.ok(id('studioStatus').textContent.includes('Datos: 10 planes'),'Sources did not load: '+id('studioStatus').textContent);
 assert.equal(id('studioMonth').options.length,11,'10 months filter');
 assert.equal(id('studioModel').options.length,7,'Six model filters');
 id('studioEdit').click();
 assert.equal(id('studioTools').hidden,false,'Edit mode expands controls in Resumen');
 assert.equal(id('studioCards').querySelectorAll('.studio-native-tools').length,5,'All native widgets editable');
 const native=id('c3ComparePanel');
 native.querySelector('[data-native-size]').value="6";
 native.querySelector('[data-native-size]').dispatchEvent(new w.Event('change'));
 assert.equal(native.style.gridColumn,'span 6','Native widget can resize');
 native.querySelector('[data-native-act="down"]').click();
 assert.notEqual(id('studioCards').firstElementChild.id,'c3ComparePanel','Native widget can move');
 id('studioAdd').click();
 assert.equal(id('studioCards').querySelectorAll('.studio-card').length,1,'Can add graph inline');
 id('studioCompare').click();
 assert.equal(id('studioCards').querySelectorAll('.studio-card').length,2,'Can add comparison inline');
 let card=id('studioCards').lastElementChild;
 assert.ok(card.querySelector('[data-control="source"]').value==='compare','Comparison source selectable');
 const label=card.querySelector('.studio-card-title');
 label.value='Gráfico personalizado';
 label.dispatchEvent(new w.Event('change'));
 assert.ok(id('studioCards').lastElementChild.querySelector('.studio-card-title').value==='Gráfico personalizado','Editable title did not update');
 card=id('studioCards').lastElementChild;
 card.querySelector('[data-control="chart"]').value='table';
 card.querySelector('[data-control="chart"]').dispatchEvent(new w.Event('change'));
 assert.ok(id('studioCards').lastElementChild.querySelector('table'),'Table view available');
 id('studioMonth').value='2026-05';
 id('studioMonth').dispatchEvent(new w.Event('change'));
 assert.ok(id('studioCards').textContent.includes('Mayo'),'May discrepancy visible');
 id('studioSave').click();
 assert.ok(w.localStorage.getItem('citroen_workspace_summary_v2'),'View saved to localStorage');
 id('studioReset').click();
 assert.equal(id('studioCards').querySelectorAll('.studio-card').length,0,'Reset clears custom cards');
 assert.equal(id('studioCards').querySelectorAll('.c3-panel').length,5,'Reset preserves the original five widgets');
 console.log('PASS: Citroen Resumen inline editor with native layouts, custom charts, comparisons, table, filters, save, reset and corrected 2026 planning.');
 w.close();
})().catch(e=>{console.error(e);process.exitCode=1;w.close();});
